CREATE OR REPLACE FUNCTION helioscta_app.touch_criterion_watchlist_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  target_watchlist_id integer;
BEGIN
  target_watchlist_id := COALESCE(NEW.watchlist_id, OLD.watchlist_id);

  UPDATE helioscta_app.criterion_watchlists
  SET updated_at = now()
  WHERE watchlist_id = target_watchlist_id;

  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_touch_criterion_watchlist_updated_at
AFTER INSERT OR UPDATE OR DELETE
ON helioscta_app.criterion_watchlist_items
FOR EACH ROW
EXECUTE FUNCTION helioscta_app.touch_criterion_watchlist_updated_at();

DROP FUNCTION IF EXISTS helioscta_app.touch_criterion_power_plant_watchlist_updated_at();
