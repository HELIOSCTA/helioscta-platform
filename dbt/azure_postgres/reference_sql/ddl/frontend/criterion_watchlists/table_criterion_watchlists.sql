CREATE TABLE IF NOT EXISTS helioscta_app.criterion_watchlist_items (
  watchlist_id integer NOT NULL,
  entity_type text NOT NULL DEFAULT 'nomination_point',
  source_table text NOT NULL DEFAULT 'PRODUCTION.PIPELINES.NOMINATION_POINTS',
  source_key text NOT NULL,
  tsp_short text,
  metadata_id text,
  display_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  source_attrs jsonb NOT NULL DEFAULT '{}'::jsonb,
  display_name_override text,
  sort_order integer,
  created_by varchar(255),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT criterion_watchlist_items_pkey
    PRIMARY KEY (watchlist_id, entity_type, source_table, source_key),
  CONSTRAINT fk_criterion_watchlist_items_watchlist
    FOREIGN KEY (watchlist_id)
    REFERENCES helioscta_app.criterion_watchlists (watchlist_id)
    ON DELETE CASCADE,
  CONSTRAINT chk_criterion_watchlist_items_entity_type_nonempty
    CHECK (length(trim(entity_type)) > 0),
  CONSTRAINT chk_criterion_watchlist_items_source_table_nonempty
    CHECK (length(trim(source_table)) > 0),
  CONSTRAINT chk_criterion_watchlist_items_source_key_nonempty
    CHECK (length(trim(source_key)) > 0),
  CONSTRAINT chk_criterion_watchlist_items_display_snapshot_object
    CHECK (jsonb_typeof(display_snapshot) = 'object'),
  CONSTRAINT chk_criterion_watchlist_items_source_attrs_object
    CHECK (jsonb_typeof(source_attrs) = 'object'),
  CONSTRAINT chk_criterion_watchlist_items_nomination_key
    CHECK (
      entity_type <> 'nomination_point'
      OR (
        tsp_short IS NOT NULL
        AND length(trim(tsp_short)) > 0
        AND metadata_id IS NOT NULL
        AND length(trim(metadata_id)) > 0
      )
    )
);

ALTER TABLE helioscta_app.criterion_watchlist_items
  ADD COLUMN IF NOT EXISTS entity_type text,
  ADD COLUMN IF NOT EXISTS source_key text,
  ADD COLUMN IF NOT EXISTS display_snapshot jsonb,
  ADD COLUMN IF NOT EXISTS source_attrs jsonb;

UPDATE helioscta_app.criterion_watchlist_items
SET entity_type = 'nomination_point'
WHERE entity_type IS NULL
   OR length(trim(entity_type)) = 0;

UPDATE helioscta_app.criterion_watchlist_items
SET source_key = tsp_short || '|' || metadata_id
WHERE (source_key IS NULL OR length(trim(source_key)) = 0)
  AND tsp_short IS NOT NULL
  AND metadata_id IS NOT NULL;

DO $$
DECLARE
  has_legacy_snapshot_columns boolean;
BEGIN
  SELECT EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'helioscta_app'
      AND table_name = 'criterion_watchlist_items'
      AND column_name = 'state_abb'
  )
  INTO has_legacy_snapshot_columns;

  IF has_legacy_snapshot_columns THEN
    UPDATE helioscta_app.criterion_watchlist_items
    SET display_snapshot = CASE
          WHEN display_snapshot IS NULL OR display_snapshot = '{}'::jsonb THEN
            jsonb_strip_nulls(
              jsonb_build_object(
                'state', state_abb,
                'pipeline', pipeline_name,
                'location', location_name,
                'locationId', location_id,
                'county', county_name,
                'connectingEntity', connecting_entity
              )
            )
          ELSE display_snapshot
        END,
        source_attrs = CASE
          WHEN source_attrs IS NULL OR source_attrs = '{}'::jsonb THEN
            jsonb_strip_nulls(
              jsonb_build_object(
                'categoryShort', category_short,
                'locQtiShort', loc_qti_short,
                'recDelSign', rec_del_sign
              )
            )
          ELSE source_attrs
        END;
  END IF;
END;
$$;

UPDATE helioscta_app.criterion_watchlist_items
SET display_snapshot = '{}'::jsonb
WHERE display_snapshot IS NULL;

UPDATE helioscta_app.criterion_watchlist_items
SET source_attrs = '{}'::jsonb
WHERE source_attrs IS NULL;

