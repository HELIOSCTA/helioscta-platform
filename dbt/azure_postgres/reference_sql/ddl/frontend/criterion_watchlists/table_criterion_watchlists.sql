/*
Criterion watchlists.

Source system: Criterion Snowflake PRODUCTION.PIPELINES. The frontend reads
plant nominations and plant-point metadata from:

- PRODUCTION.PIPELINES.METADATA
- PRODUCTION.PIPELINES.NOMINATION_POINTS

Postgres stores only app-owned saved selections.

Primary grain:
- helioscta_app.criterion_watchlists: one row per shared saved Criterion
  watchlist. watchlist_type identifies the workflow, for example
  pjm_power_plants.
- helioscta_app.criterion_watchlist_items: one row per watchlist x entity_type
  x Criterion source table x source_key membership.

For nomination_point items, source_key is tsp_short || '|' || metadata_id.
tsp_short and metadata_id are retained as typed join keys for Snowflake
validation and filtering. display_snapshot and source_attrs are non-canonical
Criterion metadata snapshots for UI display and audit context.

Saved item membership is canonical. filter_config is retained only for UI
defaults and staging filter context, not as the selected item set.
*/

CREATE SCHEMA IF NOT EXISTS helioscta_app;

DO $$
BEGIN
  IF to_regclass('helioscta_app.criterion_watchlists') IS NULL
     AND to_regclass('helioscta_app.criterion_power_plant_watchlists') IS NOT NULL THEN
    ALTER TABLE helioscta_app.criterion_power_plant_watchlists
      RENAME TO criterion_watchlists;
  END IF;

  IF to_regclass('helioscta_app.criterion_watchlist_items') IS NULL
     AND to_regclass('helioscta_app.criterion_power_plant_watchlist_points') IS NOT NULL THEN
    ALTER TABLE helioscta_app.criterion_power_plant_watchlist_points
      RENAME TO criterion_watchlist_items;
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS helioscta_app.criterion_watchlists (
  watchlist_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL,
  display_name text NOT NULL,
  watchlist_type text NOT NULL DEFAULT 'pjm_power_plants',
  source_system text NOT NULL DEFAULT 'criterion',
  filter_config jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by varchar(255),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  is_active boolean NOT NULL DEFAULT true,
  CONSTRAINT chk_criterion_watchlists_slug_nonempty
    CHECK (length(trim(slug)) > 0),
  CONSTRAINT chk_criterion_watchlists_display_name_nonempty
    CHECK (length(trim(display_name)) > 0),
  CONSTRAINT chk_criterion_watchlists_type_nonempty
    CHECK (length(trim(watchlist_type)) > 0),
  CONSTRAINT chk_criterion_watchlists_source_system_nonempty
    CHECK (length(trim(source_system)) > 0),
  CONSTRAINT chk_criterion_watchlists_filter_config_object
    CHECK (jsonb_typeof(filter_config) = 'object')
);

ALTER TABLE helioscta_app.criterion_watchlists
  ADD COLUMN IF NOT EXISTS watchlist_type text,
  ADD COLUMN IF NOT EXISTS source_system text;

UPDATE helioscta_app.criterion_watchlists
SET watchlist_type = 'pjm_power_plants'
WHERE watchlist_type IS NULL
   OR length(trim(watchlist_type)) = 0;

UPDATE helioscta_app.criterion_watchlists
